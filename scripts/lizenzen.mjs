// Writes THIRD-PARTY-LICENSES.md: the licenses of all third-party components built into Glowport.
// Rust via `cargo about` (settings in about.toml, template about.hbs), the interface from node_modules.
// Run in the project folder: node scripts/licenses.mjs (needs `cargo install cargo-about --features cli`).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const temp = mkdtempSync(join(tmpdir(), 'glowport-lizenzen-'));
const rustFile = join(temp, 'rust.md');
execFileSync('cargo', ['about', 'generate', '-m', 'src-tauri/Cargo.toml', 'about.hbs', '-o', rustFile], { stdio: ['ignore', 'inherit', 'inherit'] });
const rust = readFileSync(rustFile, 'utf8').trim();
rmSync(temp, { recursive: true, force: true });

// What the interface brings along: all packages in the lockfile except those only for development.
const lock = JSON.parse(readFileSync('package-lock.json', 'utf8'));
const groups = new Map();
for (const [path, meta] of Object.entries(lock.packages)) {
  if (!path || meta.dev || meta.devOptional) continue;
  const dir = path;
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const license = typeof manifest.license === 'string' ? manifest.license : (manifest.license?.type ?? 'see package');
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : '';
  const name = manifest.name;
  const url = `https://www.npmjs.com/package/${name}`;
  // Same text, one group: that way every license appears only once.
  const key = `${license}\n${text}`;
  if (!groups.has(key)) groups.set(key, { license, text, used: [] });
  groups.get(key).used.push(`- [${name} ${manifest.version}](${url})`);
}
const web = [...groups.values()]
  .sort((a, b) => a.license.localeCompare(b.license))
  .map(({ license, text, used }) => [`### ${license}`, '', ...used.sort(), '', text ? ['```text', text, '```'].join('\n') : '_The package ships no license file of its own; the license named applies._', ''].join('\n'))
  .join('\n');

const head = `# Third-party licenses

Glowport itself is licensed under the [MIT license](LICENSE). It contains the following components by other authors,
each under the license named. This file is generated by \`node scripts/lizenzen.mjs\`.

## Trademarks

The logos of operating systems, distributions and programs shown in Glowport come from [Simple Icons](https://simpleicons.org)
(CC0 1.0) and only serve to identify a server's system. All trademarks belong to their respective owners; Glowport is not
affiliated with or endorsed by them.
`;

writeFileSync('THIRD-PARTY-LICENSES.md', [head, rust, '', '## User interface', '', web].join('\n'));
console.log(`THIRD-PARTY-LICENSES.md: ${groups.size} Lizenztexte der Oberfläche, Rust aus cargo about`);
if (!existsSync('LICENSE')) throw new Error('LICENSE fehlt');
